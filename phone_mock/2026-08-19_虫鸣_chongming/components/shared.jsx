// 导航栏
function NavBar({ title, onBack, showBack = false, transparent = false }) {
  return (
    <div className="nav-bar" style={transparent ? { background: 'transparent', backdropFilter: 'none' } : {}}>
      {showBack && (
        <div className="nav-back" onClick={onBack}>
          <Icons.ChevronLeft size={22} />
        </div>
      )}
      <div className="nav-bar-title">{title}</div>
    </div>
  );
}

// TabBar
function TabBar({ activeTab, onTabChange, collectionRef }) {
  const tabs = [
    { key: 'tonight', label: '今夜', icon: Icons.Moon },
    { key: 'collection', label: '虫谱', icon: Icons.Collection },
    { key: 'journal', label: '手账', icon: Icons.Book },
    { key: 'profile', label: '我的', icon: Icons.User },
  ];

  return (
    <div className="tab-bar">
      {tabs.map(tab => (
        <div
          key={tab.key}
          className={`tab-item ${activeTab === tab.key ? 'active' : ''}`}
          onClick={() => onTabChange(tab.key)}
        >
          <div ref={tab.key === 'collection' ? collectionRef : null}>
            <tab.icon size={24} />
          </div>
          <span className="tab-label">{tab.label}</span>
        </div>
      ))}
    </div>
  );
}

// 状态栏时间显示
function getTimeString() {
  const now = new Date();
  return now.toLocaleTimeString('zh-CN', { hour: '2-digit', minute: '2-digit', hour12: false });
}

window.Icons = Icons;
window.NavBar = NavBar;
window.TabBar = TabBar;
window.getTimeString = getTimeString;
